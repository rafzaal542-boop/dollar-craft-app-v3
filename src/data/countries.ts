export function getDialCodeForCountry(countryInput: string): string {
  if (!countryInput) return '';
  const match = ALL_COUNTRIES.find(
    (c) =>
      countryInput.includes(c.name) ||
      countryInput.includes(c.code) ||
      c.name.toLowerCase() === countryInput.toLowerCase() ||
      c.code.toLowerCase() === countryInput.toLowerCase()
  );
  return match ? match.dialCode : '';
}
